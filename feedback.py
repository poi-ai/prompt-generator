"""作業完了後に投げる、元の指示文へのフィードバックを求めるプロンプトを組み立てる

会話の途中でセッションを切り替えるケースがあるため、「先ほどの指示文」のような
会話上の位置に頼った参照はせず、元の指示文の全文をそのまま引用として埋め込む。
"""


def build(original_prompt: str) -> str:
    quoted_lines = [f"> {line}" if line else ">" for line in original_prompt.rstrip("\n").split("\n")]

    return (
        "# フィードバック依頼\n\n"
        "これは、下記の【元の指示文】に基づいて行っていただいた作業についてのフィードバック依頼です。\n"
        "その後の計画のすり合わせや、作業中に出した修正指示は対象外です。"
        "**【元の指示文】そのもの**について、以下の観点で率直な意見をください。\n\n"
        "## 【元の指示文】\n\n"
        + "\n".join(quoted_lines) + "\n\n"
        "## フィードバックしてほしい観点\n\n"
        "- 【元の指示文】の情報だけでは判断できず、独自に推測・仮定して進めた箇所はありましたか? あれば具体的に教えてください。\n"
        "- 【元の指示文】の中で、曖昧だった・複数の解釈ができた箇所はありましたか?\n"
        "- 作業を進める上で、【元の指示文】に事前に書かれていれば助かった情報があれば教えてください。\n"
        "- 逆に、【元の指示文】の中で不要だった・作業に活かせなかった情報はありましたか?\n"
        "- 上記を踏まえて、次回同様の依頼をする際に【元の指示文】へ追加・修正すべき点を具体的に提案してください。\n"
    )
